TRANSLATIONS.update(REGIONAL)

def escape_xml(val):
    return val.replace("&", "&amp;").replace("'", "\\'").replace('"', '\\"')

res_dir = "/app/applet/app/src/main/res"
if not os.path.exists(res_dir):
    res_dir = "app/src/main/res"

print(f"Using res_dir: {res_dir}")

for item in os.listdir(res_dir):
    if item.startswith("values-"):
        lang_code = item.replace("values-", "")
        xml_path = os.path.join(res_dir, item, "strings.xml")
        if not os.path.exists(xml_path):
            continue
        
        # Get translations for this language
        lang_dict = TRANSLATIONS.get(lang_code)
        if not lang_dict:
            lang_dict = generate_generic_translations(lang_code)
            
        with open(xml_path, "r", encoding="utf-8") as f:
            content = f.read()
            
        # Parse or append missing keys before </resources>
        lines_to_add = []
        for key, value in lang_dict.items():
            tag_str = f'name="{key}"'
            if tag_str not in content:
                escaped_val = value.replace("&amp;", "&") # unescape first if any
                escaped_val = escape_xml(escaped_val)
                lines_to_add.append(f'    <string name="{key}">{escaped_val}</string>')
                
        if lines_to_add:
            insert_pos = content.rfind("</resources>")
            if insert_pos != -1:
                new_content = content[:insert_pos] + "\n".join(lines_to_add) + "\n" + content[insert_pos:]
                with open(xml_path, "w", encoding="utf-8") as f:
                    f.write(new_content)
                print(f"Updated {xml_path} with {len(lines_to_add)} keys")

print("All translation updates completed!")
